#!/usr/bin/env python3
"""Regenerate the committed assets for the BambuHelper M5Tab5 Arduino sketch.

This replaces two PlatformIO-only mechanisms that Arduino IDE does not have:

  board_build.embed_files  - VLW fonts linked through _binary_*_start symbols
  extra_scripts (SCons)    - web_assets_gz.h written into BUILD_DIR/generated

Arduino IDE has neither an embed step nor a pre-build hook, so the outputs are
generated here and committed as ordinary sketch sources:

  src/p4_sans_fonts.h/.cpp - character-subsetted VLW fonts as PROGMEM arrays
  src/web_assets_gz.h      - gzipped CSS/JS with content-hash version strings

The VLW subset keeps only codepoints that actually appear in the project's
sources (plus a UI fallback set), cutting 6.7 MB of full GB2312 fonts down to
roughly 230 KB. That keeps the firmware inside the board package's default
6.5 MB app slot, so no custom partition table is needed.

Re-run after changing any UI string or web asset:
    python3 tools/prepare_assets.py [--source /path/to/BambuHelper]
"""
from __future__ import annotations

import argparse
import gzip
import struct
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
SKETCH = HERE.parent
DEFAULT_SOURCE = HERE.parents[2] / "BambuHelper"

# Common dashboard / printer vocabulary kept even if no source file happens to
# mention it. Add characters here when a print job title renders as a blank box.
EXTRA_CHARS = {ord(c) for c in (
    "打印温度热床速度进度剩余时间完成失败暂停取消准备中连接断开网络配置设置保存重启"
    "恢复出厂无线信号云账号密码序列号访问码耗材层数喷嘴风扇腔体湿度电压电流"
    "小时分钟秒天周月年月日星期百分比摄氏度米毫安瓦特错误警告正常离线在线"
    "开始结束继续返回上一页下一页确认是否开启关闭亮度音量语言主题状态"
    "耗材余量校准归位自动手动首页菜单详情更多帮助关于版本更新成功"
)}

SYMBOLS = {0xB0, 0xB7, 0x2014, 0x2013, 0x2026, 0x2248, 0x00A0}


def collect_charset(source: Path) -> set[int]:
    chars = set(range(32, 127)) | SYMBOLS | EXTRA_CHARS
    patterns = (
        "src/*.cpp", "src/*.h", "include/*.h", "include/fonts/*.h",
        "include/error_tables/*.h", "web/*.js", "web/*.css",
    )
    files = [p for pattern in patterns for p in source.glob(pattern)]
    files += [p for p in (SKETCH / "src").glob("*") if p.suffix in (".h", ".cpp")]
    files += list(SKETCH.glob("*.ino"))
    for path in files:
        if not path.is_file():
            continue
        try:
            for ch in path.read_text(encoding="utf-8", errors="ignore"):
                if ord(ch) > 127:
                    chars.add(ord(ch))
        except OSError:
            pass
    return chars


def subset_vlw(data: bytes, keep: set[int]) -> bytes:
    """Rebuild a Bodmer VLW font retaining only the requested glyphs.

    Layout (all big-endian u32):
      header  : count, version, font_size, padding, ascent, descent
      metrics : count * 7 u32 (unicode, height, width, advance, top, left, pad)
      bitmaps : height*width alpha bytes per glyph, in metric order
    The glyph table is searched with lower_bound, so file order must stay
    ascending - filtering an already sorted source preserves that.
    """
    count, version, size, padding, ascent, descent = struct.unpack_from(">6I", data, 0)
    off = 24
    metrics = []
    for _ in range(count):
        metrics.append(struct.unpack_from(">7I", data, off))
        off += 28
    pos = off
    entries = []
    for metric in metrics:
        length = metric[1] * metric[2]
        entries.append((metric, pos, length))
        pos += length
    if pos != len(data):
        raise ValueError("VLW bitmap section length mismatch")
    kept = [entry for entry in entries if entry[0][0] in keep]
    out = bytearray(struct.pack(">6I", len(kept), version, size,
                                padding, ascent, descent))
    for metric, _, _ in kept:
        out += struct.pack(">7I", *metric)
    for _, start, length in kept:
        out += data[start:start + length]
    return bytes(out)


def c_array(name: str, data: bytes) -> str:
    lines = [f"const uint8_t {name}[] PROGMEM = {{"]
    for i in range(0, len(data), 16):
        lines.append("  " + "".join(f"0x{b:02x}," for b in data[i:i + 16]))
    lines.append("};")
    return "\n".join(lines) + "\n"


def font_header(sizes: dict[str, int]) -> str:
    return (
        "// GENERATED by tools/prepare_assets.py - edit the script, not this file.\n"
        "// One definition lives in p4_sans_fonts.cpp; every other TU sees extern.\n"
        "#pragma once\n"
        "#include <Arduino.h>\n"
        "#include <stddef.h>\n\n"
        "extern const uint8_t p4SansData[];\n"
        "extern const uint8_t p4SansSmallData[];\n"
        f"constexpr size_t p4SansData_size = {sizes['p4SansData']};\n"
        f"constexpr size_t p4SansSmallData_size = {sizes['p4SansSmallData']};\n"
    )


def web_header(source: Path) -> str:
    body = []
    for name, relative in (("WEB_APP_CSS", "web/app.css"),
                           ("WEB_APP_JS", "web/app.js")):
        raw = (source / relative).read_bytes()
        blob = gzip.compress(raw, compresslevel=9, mtime=0)
        version = format(zlib.crc32(raw) & 0xFFFFFFFF, "08x")
        lines = [f"static const uint8_t {name}_GZ[] PROGMEM = {{"]
        for i in range(0, len(blob), 16):
            lines.append("  " + "".join(f"0x{b:02x}," for b in blob[i:i + 16]))
        lines.append("};")
        lines.append(f"static const size_t {name}_GZ_LEN = {len(blob)};")
        lines.append(f'#define {name}_VER "{version}"')
        lines.append("")
        body.append("\n".join(lines))
        print(f"  {relative}: {len(raw):,} -> {len(blob):,} bytes gzip")
    head = (
        "// GENERATED by tools/prepare_assets.py - do not edit.\n"
        "// Source of truth: web/app.css and web/app.js in the BambuHelper repo.\n"
        "// Include from one translation unit only (static storage class).\n"
        "#pragma once\n"
        "#include <Arduino.h>\n"
        "#include <pgmspace.h>\n\n"
    )
    return head + "\n".join(body)


def write_if_changed(path: Path, text: str) -> None:
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        print(f"  {path.name}: unchanged")
        return
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"  {path.name}: written ({len(text):,} bytes)")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    source = parser.parse_args().source.resolve()
    if not (source / "assets/p4/p4_sans_24.vlw").is_file():
        raise SystemExit(f"BambuHelper source project not found: {source}")

    chars = collect_charset(source)
    print(f"charset: {len(chars)} codepoints "
          f"({sum(1 for c in chars if 0x4E00 <= c <= 0x9FFF)} CJK)")

    arrays = []
    sizes: dict[str, int] = {}
    for size, symbol in ((24, "p4SansData"), (20, "p4SansSmallData")):
        raw = (source / f"assets/p4/p4_sans_{size}.vlw").read_bytes()
        cut = subset_vlw(raw, chars)
        print(f"  p4_sans_{size}.vlw: {len(raw):,} -> {len(cut):,} bytes")
        sizes[symbol] = len(cut)
        arrays.append(c_array(symbol, cut))

    write_if_changed(SKETCH / "src/p4_sans_fonts.h", font_header(sizes))
    write_if_changed(SKETCH / "src/p4_sans_fonts.cpp",
                     "// GENERATED by tools/prepare_assets.py - do not edit.\n"
                     "#include \"p4_sans_fonts.h\"\n\n" + "\n".join(arrays))
    write_if_changed(SKETCH / "src/web_assets_gz.h", web_header(source))


if __name__ == "__main__":
    main()
