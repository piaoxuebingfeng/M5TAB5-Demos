#!/usr/bin/env python3
"""Regenerate the gzipped web assets committed into this Arduino sketch.

PlatformIO used an SCons extra_script to render web/app.css + web/app.js into
BUILD_DIR/generated/web_assets_gz.h at build time. Arduino IDE has no
pre-build hook, so the gzip blob is produced here and committed as an ordinary
sketch source:

    src/web_assets_gz.h - gzipped CSS/JS with content-hash version strings

The Chinese face used to live here too. It does not any more: job titles and
printer names are user text, so the firmware now ships the complete GB2312
face instead of a source-charset subset. That blob is generated by
tools/build_cjk_font.py and needs the 15 MB app slot in partitions.csv.

Re-run after changing web/app.css or web/app.js:
    python3 tools/prepare_assets.py [--source /path/to/BambuHelper]
"""
from __future__ import annotations

import argparse
import gzip
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
SKETCH = HERE.parent
DEFAULT_SOURCE = HERE.parents[2] / "BambuHelper"


def web_header(source: Path) -> str:
    body = []
    for name, relative in (("WEB_APP_CSS", "web/app.css"),
                           ("WEB_APP_JS", "web/app.js")):
        raw = (source / relative).read_bytes()
        blob = gzip.compress(raw, compresslevel=9, mtime=0)
        version = format(zlib.crc32(raw) & 0xFFFFFFFF, "08x")
        lines = [f"static const uint8_t {name}_GZ[] PROGMEM = {{"]
        for i in range(0, len(blob), 16):
            lines.append("  " + "".join(f"0x{b:02x}," for b in blob[i:i + 16]))
        lines.append("};")
        lines.append(f"static const size_t {name}_GZ_LEN = {len(blob)};")
        lines.append(f'#define {name}_VER "{version}"')
        lines.append("")
        body.append("\n".join(lines))
        print(f"  {relative}: {len(raw):,} -> {len(blob):,} bytes gzip")
    head = (
        "// GENERATED by tools/prepare_assets.py - do not edit.\n"
        "// Source of truth: web/app.css and web/app.js in the BambuHelper repo.\n"
        "// Include from one translation unit only (static storage class).\n"
        "#pragma once\n"
        "#include <Arduino.h>\n"
        "#include <pgmspace.h>\n\n"
    )
    return head + "\n".join(body)


def write_if_changed(path: Path, text: str) -> None:
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        print(f"  {path.name}: unchanged")
        return
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"  {path.name}: written ({len(text):,} bytes)")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    source = parser.parse_args().source.resolve()
    if not (source / "web/app.js").is_file():
        raise SystemExit(f"BambuHelper source project not found: {source}")

    write_if_changed(SKETCH / "src/web_assets_gz.h", web_header(source))


if __name__ == "__main__":
    main()
