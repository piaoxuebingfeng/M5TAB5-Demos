#!/usr/bin/env python3
"""Generate src/p4_sans_fonts.{h,cpp} - the dashboard's Chinese face.

Why this exists separately from prepare_assets.py:

  prepare_assets.py subsets the VLW down to the codepoints that appear in the
  project sources (~380 glyphs, ~170 KB) so the firmware fits the board
  package's default 6.5 MB app slot. That is fine for chrome text, but print
  job titles and printer names are typed by the user: any GB2312 character can
  show up, and every glyph missing from the subset renders as a tofu box.

  Bambu Studio job titles are overwhelmingly common hanzi, so the face below
  carries the whole GB2312 repertoire (6763 hanzi + symbols + ASCII). It needs
  a bigger app partition; see partitions.csv in the sketch root.

Font: Noto Sans SC Regular (SIL Open Font License 1.1), weight 400, 24 px -
the same family, size and weight the 7B build uses, so the Tab5 dashboard
keeps its typography.

Usage:
    python3 tools/build_cjk_font.py [path/to/NotoSansSC.ttf] [--size 24]

Requires freetype-py (pip install freetype-py). The generated .cpp is
committed, so normal builds do not need the converter or the TTF.
"""
from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SKETCH = HERE.parent
SOURCE_SCRIPTS = HERE.parents[2] / "BambuHelper" / "scripts"

# Same glyphs generate_p4_font.py requests: printable ASCII, the UI symbols the
# dashboard uses, the complete GB2312 double-byte range, plus any non-ASCII
# character that appears in this sketch (so a typo in a literal still renders).
SYMBOLS = {0x00B0, 0x00B7, 0x2014, 0x2013, 0x2026, 0x2248, 0x2713}


def charset(sketch: Path) -> list[int]:
    chars = set(range(32, 127)) | SYMBOLS
    for high in range(0xA1, 0xF8):
        for low in range(0xA1, 0xFF):
            try:
                chars.add(ord(bytes([high, low]).decode("gb2312")))
            except UnicodeDecodeError:
                continue
    for path in list((sketch / "src").glob("*.cpp")) + list((sketch / "src").glob("*.h")):
        chars.update(ord(c) for c in path.read_text(errors="ignore") if ord(c) > 127)
    return sorted(chars)


def generate(ttf: Path, size: int, codepoints: list[int]) -> bytes:
    import freetype
    sys.path.insert(0, str(SOURCE_SCRIPTS))
    from generate_vlw_fonts import generate_vlw  # noqa: E402  (needs sys.path)

    # The Google Fonts build is a static Regular; a variable TTF (the Windows
    # NotoSansSC-VF.ttf) needs wght pinned to the same 400 weight. freetype
    # raises on get_variation_info() for fonts without an fvar table.
    try:
        variable = freetype.Face(str(ttf)).get_variation_info() is not None
    except Exception:
        variable = False
    return generate_vlw(str(ttf), size, codepoints, weight=400 if variable else None)


def cpp_array(name: str, data: bytes) -> str:
    lines = [f"const uint8_t {name}[] PROGMEM = {{"]
    for i in range(0, len(data), 20):
        chunk = ",".join(f"0x{b:02x}" for b in data[i:i + 20])
        lines.append("  " + chunk + ",")
    lines.append("};")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("ttf", nargs="?", default="/usr/share/fonts/truetype/noto/NotoSansSC-Regular.ttf")
    ap.add_argument("--size", type=int, default=24)
    args = ap.parse_args()

    ttf = Path(args.ttf)
    if not ttf.is_file():
        print(f"TTC/TTF not found: {ttf}")
        print("Download Noto Sans SC (OFL) and pass it as the first argument.")
        return 1

    chars = charset(SKETCH)
    print(f"charset: {len(chars)} codepoints ({sum(1 for c in chars if c > 0x2000)} CJK/symbols)")
    data = generate(ttf, args.size, chars)
    print(f"{args.size}px full GB2312 VLW: {len(data):,} bytes")

    (SKETCH / "src" / "p4_sans_fonts.h").write_text(
        "// GENERATED by tools/build_cjk_font.py - edit the script, not this file.\n"
        "// One definition lives in p4_sans_fonts.cpp; every other TU sees extern.\n"
        "#pragma once\n"
        "#include <Arduino.h>\n"
        "#include <stddef.h>\n\n"
        "// Complete GB2312 face (Noto Sans SC 24px) for dynamic text: printer\n"
        "// names, print job titles, HMS strings that arrive from the cloud.\n"
        "extern const uint8_t p4SansData[];\n"
        f"constexpr size_t p4SansData_size = {len(data)};\n"
    )
    (SKETCH / "src" / "p4_sans_fonts.cpp").write_text(
        "// GENERATED by tools/build_cjk_font.py - do not edit.\n"
        '#include "p4_sans_fonts.h"\n\n' + cpp_array("p4SansData", data) + "\n"
    )
    print("wrote src/p4_sans_fonts.h/.cpp")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
